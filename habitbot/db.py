"""Хранилище: пользователи, привычки и ответы по дням.

Ответ за день бывает трёх видов: «да» (полезная сделана, вредная была), «нет» и «нет данных».
«Да» и «нет» — строки таблицы `marks` со значением 1 и 0; «нет данных» — отсутствие строки.

Две базы на выбор: PostgreSQL (адрес `postgresql://…`) — для сервера, SQLite (путь к файлу) —
для локального запуска и тестов. Запросы написаны на общем для обеих диалекте; различаются
только знак подстановки и создание схемы.
"""

from __future__ import annotations

import sqlite3
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import UTC, date, datetime, timedelta

GOOD = "good"
BAD = "bad"

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER PRIMARY KEY,
    tz TEXT NOT NULL,
    referred_by INTEGER,
    name TEXT,
    username TEXT,
    joined_at TEXT
);
CREATE TABLE IF NOT EXISTS habits (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL REFERENCES users(user_id),
    name TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('good', 'bad')),
    emoji TEXT,
    remind_at TEXT,
    created_on TEXT NOT NULL,
    archived INTEGER NOT NULL DEFAULT 0,
    last_reminded TEXT
);
CREATE TABLE IF NOT EXISTS marks (
    habit_id INTEGER NOT NULL REFERENCES habits(id) ON DELETE CASCADE,
    day TEXT NOT NULL,
    value INTEGER NOT NULL DEFAULT 1,
    PRIMARY KEY (habit_id, day)
);
CREATE TABLE IF NOT EXISTS shares (
    key TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL,
    file_id TEXT NOT NULL,
    caption TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_habits_user ON habits(user_id, archived);
"""


# В PostgreSQL идентификаторы Telegram не помещаются в INTEGER — нужны BIGINT. Даты и время
# хранятся текстом в формате ISO, как и в SQLite: так код и перенос данных одинаковы.
PG_SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT PRIMARY KEY,
    tz TEXT NOT NULL,
    referred_by BIGINT,
    name TEXT,
    username TEXT,
    joined_at TEXT
);
CREATE TABLE IF NOT EXISTS habits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    name TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('good', 'bad')),
    emoji TEXT,
    remind_at TEXT,
    created_on TEXT NOT NULL,
    archived INTEGER NOT NULL DEFAULT 0,
    last_reminded TEXT
);
CREATE TABLE IF NOT EXISTS marks (
    habit_id BIGINT NOT NULL REFERENCES habits(id) ON DELETE CASCADE,
    day TEXT NOT NULL,
    value INTEGER NOT NULL DEFAULT 1,
    PRIMARY KEY (habit_id, day)
);
CREATE TABLE IF NOT EXISTS shares (
    key TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    file_id TEXT NOT NULL,
    caption TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_habits_user ON habits(user_id, archived);
"""

TABLES = ("users", "habits", "marks", "shares")


def is_postgres(target: str) -> bool:
    return target.startswith(("postgresql://", "postgres://"))


class PgConnection:
    """Соединение с PostgreSQL с тем же набором вызовов, что у sqlite3.

    Каждый запрос фиксируется сразу. Если соединение оборвалось (базу перезапустили),
    подключаемся заново и повторяем запрос один раз — бот не должен падать из-за этого.
    """

    def __init__(self, url: str) -> None:
        import psycopg
        from psycopg.rows import dict_row

        self._psycopg = psycopg
        self._row_factory = dict_row
        self._url = url
        self._connect()

    def _connect(self) -> None:
        self.raw = self._psycopg.connect(self._url, autocommit=True, row_factory=self._row_factory)

    def execute(self, sql: str, params: Sequence[object] = ()):
        query = sql.replace("?", "%s")
        try:
            return self.raw.execute(query, params)
        except (self._psycopg.OperationalError, self._psycopg.InterfaceError):
            self._connect()
            return self.raw.execute(query, params)

    def commit(self) -> None:
        """Ничего не делает: запросы фиксируются сразу."""

    def close(self) -> None:
        self.raw.close()


@dataclass(frozen=True)
class Habit:
    id: int
    user_id: int
    name: str
    kind: str
    emoji: str | None
    remind_at: str | None
    created_on: date
    last_reminded: date | None

    @property
    def is_bad(self) -> bool:
        return self.kind == BAD

    @property
    def icon(self) -> str:
        """Эмодзи привычки; у заведённых до появления выбора — значок по типу."""
        return self.emoji or ("🚫" if self.is_bad else "✅")


@dataclass(frozen=True)
class Invited:
    """Человек, пришедший по приглашению."""

    user_id: int
    name: str | None
    username: str | None
    joined_at: datetime | None  # UTC; пусто у пришедших до того, как время стали записывать


def _now() -> str:
    """Текущий момент в UTC с точностью до секунды — для хранения."""
    return datetime.now(UTC).replace(microsecond=0).isoformat()


def _habit(row: Mapping[str, object]) -> Habit:
    return Habit(
        id=row["id"],
        user_id=row["user_id"],
        name=row["name"],
        kind=row["kind"],
        emoji=row["emoji"],
        remind_at=row["remind_at"],
        created_on=date.fromisoformat(row["created_on"]),
        last_reminded=date.fromisoformat(row["last_reminded"]) if row["last_reminded"] else None,
    )


class Storage:
    """Синхронные запросы: они крошечные, пул соединений такому боту не нужен."""

    def __init__(self, target: str, default_tz: str = "Europe/Moscow") -> None:
        self.default_tz = default_tz
        self.postgres = is_postgres(target)
        if self.postgres:
            self.conn = PgConnection(target)
            self.conn.execute(PG_SCHEMA)
            # База, созданная до появления ответа «нет»: прежние отметки — это «да».
            self.conn.execute(
                "ALTER TABLE marks ADD COLUMN IF NOT EXISTS value INTEGER NOT NULL DEFAULT 1"
            )
            return
        self.conn = sqlite3.connect(target)
        self.conn.row_factory = sqlite3.Row
        self.conn.execute("PRAGMA foreign_keys = ON")
        self.conn.executescript(SCHEMA)
        # База, созданная до появления эмодзи: добавляем колонку на месте.
        columns = {row["name"] for row in self.conn.execute("PRAGMA table_info(habits)")}
        if "emoji" not in columns:
            self.conn.execute("ALTER TABLE habits ADD COLUMN emoji TEXT")
        # То же для приглашений.
        columns = {row["name"] for row in self.conn.execute("PRAGMA table_info(users)")}
        if "referred_by" not in columns:
            self.conn.execute("ALTER TABLE users ADD COLUMN referred_by INTEGER")
        # Имя, ник и время первого прихода: у пришедших раньше время остаётся пустым.
        for column in ("name", "username", "joined_at"):
            if column not in columns:
                self.conn.execute(f"ALTER TABLE users ADD COLUMN {column} TEXT")
        # Ответ «нет»: прежние отметки — это «да».
        columns = {row["name"] for row in self.conn.execute("PRAGMA table_info(marks)")}
        if "value" not in columns:
            self.conn.execute("ALTER TABLE marks ADD COLUMN value INTEGER NOT NULL DEFAULT 1")
        self.conn.commit()

    # --- пользователи ---

    def ensure_user(self, user_id: int) -> None:
        self.conn.execute(
            "INSERT INTO users (user_id, tz, joined_at) VALUES (?, ?, ?) ON CONFLICT DO NOTHING",
            (user_id, self.default_tz, _now()),
        )
        self.conn.commit()

    def touch_user(self, user_id: int, name: str | None, username: str | None) -> None:
        """Обновляет имя и ник уже известного пользователя; новых не заводит — иначе первый
        вход по приглашению перестал бы считаться первым."""
        self.conn.execute(
            "UPDATE users SET name = ?, username = ? WHERE user_id = ? "
            "AND (name IS DISTINCT FROM ? OR username IS DISTINCT FROM ?)",
            (name, username, user_id, name, username),
        )
        self.conn.commit()

    def invited(self, user_id: int) -> list[Invited]:
        """Кто пришёл по ссылке пользователя, новые сверху."""
        rows = self.conn.execute(
            "SELECT user_id, name, username, joined_at FROM users WHERE referred_by = ? "
            "ORDER BY joined_at DESC, user_id DESC",
            (user_id,),
        ).fetchall()
        return [
            Invited(
                user_id=r["user_id"],
                name=r["name"],
                username=r["username"],
                joined_at=datetime.fromisoformat(r["joined_at"]) if r["joined_at"] else None,
            )
            for r in rows
        ]

    def register(self, user_id: int, referred_by: int | None = None) -> bool:
        """Заводит пользователя; `True` — если он новый и пришёл по действующему приглашению.

        Приглашение засчитывается один раз, при первом входе: себе самому и от неизвестного
        пользователя — нет, повторный переход по ссылке ничего не меняет.
        """
        known = self.conn.execute("SELECT 1 FROM users WHERE user_id = ?", (user_id,)).fetchone()
        if known:
            return False
        inviter = None
        if referred_by is not None and referred_by != user_id:
            row = self.conn.execute(
                "SELECT 1 FROM users WHERE user_id = ?", (referred_by,)
            ).fetchone()
            inviter = referred_by if row else None
        self.conn.execute(
            "INSERT INTO users (user_id, tz, referred_by, joined_at) VALUES (?, ?, ?, ?)",
            (user_id, self.default_tz, inviter, _now()),
        )
        self.conn.commit()
        return inviter is not None

    def invited_count(self, user_id: int) -> int:
        row = self.conn.execute(
            "SELECT COUNT(*) AS n FROM users WHERE referred_by = ?", (user_id,)
        ).fetchone()
        return int(row["n"])

    # --- календари, которыми делятся через выбор чата ---

    def save_share(self, key: str, user_id: int, file_id: str, caption: str) -> None:
        self.conn.execute(
            "INSERT INTO shares (key, user_id, file_id, caption) VALUES (?, ?, ?, ?) "
            "ON CONFLICT (key) DO UPDATE SET user_id = excluded.user_id, "
            "file_id = excluded.file_id, caption = excluded.caption",
            (key, user_id, file_id, caption),
        )
        self.conn.commit()

    def get_share(self, key: str, user_id: int) -> tuple[str, str] | None:
        """Картинка и подпись по ключу — только своему владельцу."""
        row = self.conn.execute(
            "SELECT file_id, caption FROM shares WHERE key = ? AND user_id = ?", (key, user_id)
        ).fetchone()
        return (row["file_id"], row["caption"]) if row else None

    def get_tz(self, user_id: int) -> str:
        row = self.conn.execute("SELECT tz FROM users WHERE user_id = ?", (user_id,)).fetchone()
        return row["tz"] if row else self.default_tz

    def set_tz(self, user_id: int, tz: str) -> None:
        self.ensure_user(user_id)
        self.conn.execute("UPDATE users SET tz = ? WHERE user_id = ?", (tz, user_id))
        self.conn.commit()

    # --- привычки ---

    def add_habit(
        self,
        user_id: int,
        name: str,
        kind: str,
        remind_at: str | None,
        today: date,
        emoji: str | None = None,
    ) -> Habit:
        self.ensure_user(user_id)
        cur = self.conn.execute(
            "INSERT INTO habits (user_id, name, kind, emoji, remind_at, created_on) "
            "VALUES (?, ?, ?, ?, ?, ?) RETURNING id",
            (user_id, name, kind, emoji, remind_at, today.isoformat()),
        )
        habit_id = int(cur.fetchone()["id"])  # до фиксации: так требует SQLite
        self.conn.commit()
        habit = self.get_habit(user_id, habit_id)
        assert habit is not None
        return habit

    def list_habits(self, user_id: int) -> list[Habit]:
        rows = self.conn.execute(
            "SELECT * FROM habits WHERE user_id = ? AND archived = 0 ORDER BY id", (user_id,)
        ).fetchall()
        return [_habit(r) for r in rows]

    def get_habit(self, user_id: int, habit_id: int) -> Habit | None:
        """Привычка только своего владельца — чужой id из кнопки ничего не откроет."""
        row = self.conn.execute(
            "SELECT * FROM habits WHERE id = ? AND user_id = ? AND archived = 0",
            (habit_id, user_id),
        ).fetchone()
        return _habit(row) if row else None

    def delete_habit(self, user_id: int, habit_id: int) -> bool:
        cur = self.conn.execute(
            "UPDATE habits SET archived = 1 WHERE id = ? AND user_id = ?", (habit_id, user_id)
        )
        self.conn.commit()
        return cur.rowcount > 0

    def set_emoji(self, user_id: int, habit_id: int, emoji: str) -> bool:
        cur = self.conn.execute(
            "UPDATE habits SET emoji = ? WHERE id = ? AND user_id = ?", (emoji, habit_id, user_id)
        )
        self.conn.commit()
        return cur.rowcount > 0

    def backdate(self, habit_id: int, day: date) -> None:
        """Сдвигает начало учёта назад, если отметили день раньше заведения привычки."""
        self.conn.execute(
            "UPDATE habits SET created_on = ? WHERE id = ? AND created_on > ?",
            (day.isoformat(), habit_id, day.isoformat()),
        )
        self.conn.commit()

    def set_reminder(self, user_id: int, habit_id: int, remind_at: str | None) -> bool:
        cur = self.conn.execute(
            "UPDATE habits SET remind_at = ?, last_reminded = NULL WHERE id = ? AND user_id = ?",
            (remind_at, habit_id, user_id),
        )
        self.conn.commit()
        return cur.rowcount > 0

    def habits_with_reminders(self) -> list[Habit]:
        rows = self.conn.execute(
            "SELECT * FROM habits WHERE archived = 0 AND remind_at IS NOT NULL"
        ).fetchall()
        return [_habit(r) for r in rows]

    def mark_reminded(self, habit_id: int, day: date) -> None:
        self.conn.execute(
            "UPDATE habits SET last_reminded = ? WHERE id = ?", (day.isoformat(), habit_id)
        )
        self.conn.commit()

    # --- ответы по дням ---

    def get_answer(self, habit_id: int, day: date) -> bool | None:
        """Ответ за день: `True` — да, `False` — нет, `None` — нет данных."""
        row = self.conn.execute(
            "SELECT value FROM marks WHERE habit_id = ? AND day = ?", (habit_id, day.isoformat())
        ).fetchone()
        return bool(row["value"]) if row else None

    def set_answer(self, habit_id: int, day: date, value: bool | None) -> None:
        """Записывает ответ за день; `None` стирает его — снова «нет данных»."""
        if value is None:
            self.conn.execute(
                "DELETE FROM marks WHERE habit_id = ? AND day = ?", (habit_id, day.isoformat())
            )
        else:
            self.conn.execute(
                "INSERT INTO marks (habit_id, day, value) VALUES (?, ?, ?) "
                "ON CONFLICT (habit_id, day) DO UPDATE SET value = excluded.value",
                (habit_id, day.isoformat(), int(value)),
            )
        self.conn.commit()

    def cycle_answer(self, habit_id: int, day: date) -> bool | None:
        """Следующий ответ по кругу: нет данных → да → нет → нет данных; возвращает новый."""
        value = {None: True, True: False, False: None}[self.get_answer(habit_id, day)]
        self.set_answer(habit_id, day, value)
        return value

    def all_answers(self, habit_id: int) -> dict[date, bool]:
        """Все ответы привычки; дней без данных в словаре нет."""
        rows = self.conn.execute(
            "SELECT day, value FROM marks WHERE habit_id = ?", (habit_id,)
        ).fetchall()
        return {date.fromisoformat(r["day"]): bool(r["value"]) for r in rows}

    def is_marked(self, habit_id: int, day: date) -> bool:
        """Есть ли за день ответ «да»."""
        return self.get_answer(habit_id, day) is True

    def all_marks(self, habit_id: int) -> set[date]:
        """Дни с ответом «да» — по ним считаются серии и число отметок."""
        return {day for day, value in self.all_answers(habit_id).items() if value}


def streak(habit: Habit, marks: set[date], today: date) -> int:
    """Текущая серия в днях.

    Полезная привычка — сколько дней подряд она отмечена (сегодня ещё не отмечена — серия
    считается по вчера, она не «сгорает» с утра). Вредная — сколько дней подряд её не было,
    считая с дня создания.
    """
    if habit.is_bad:
        day, count = today, 0
        while day >= habit.created_on and day not in marks:
            count += 1
            day -= timedelta(days=1)
        return count
    day = today if today in marks else today - timedelta(days=1)
    count = 0
    while day in marks:
        count += 1
        day -= timedelta(days=1)
    return count


def best_clean_streak(habit: Habit, marks: set[date], today: date) -> int:
    """Лучшая серия вредной привычки: самый длинный отрезок дней без срыва с начала учёта.

    Считается по сегодняшний день включительно, поэтому текущая серия в неё входит и лучшая
    никогда не меньше текущей.
    """
    best = 0
    start = habit.created_on  # первый день очередного чистого отрезка
    for slip in sorted(d for d in marks if habit.created_on <= d <= today):
        best = max(best, (slip - start).days)
        start = slip + timedelta(days=1)
    return max(best, (today - start).days + 1, 0)
